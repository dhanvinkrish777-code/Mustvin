import React, { useState } from 'react';
import { useJarvisSession } from '../contexts/JarvisSessionContext';
import {
  createGooglePresentation,
  createGoogleDoc,
  createGoogleSheet,
  createGmailDraft,
  sendGmailMessage,
  applyThemeToPresentation,
} from '../services/googleWorkspaceService';
import {
  createNewExcelWorkbook,
  downloadExcelFile,
} from '../services/excelService';
import type { SlideTheme } from '../services/aiWorkspaceClient';

export interface WorkspaceEmailPayload {
  to: string;
  subject: string;
  body: string;
}

export interface WorkspaceActionPayload {
  type: 'slides' | 'doc' | 'sheet' | 'excel' | 'email';
  title: string;
  summary: string;
  slides?: Array<{ title: string; bullets: string[]; subtitle?: string }>;
  theme?: SlideTheme;
  docContent?: string;
  headers?: string[];
  rows?: any[][];
  emailData?: WorkspaceEmailPayload;
  createdUrl?: string;
  createdId?: string;
}

interface WorkspaceActionCardProps {
  action: WorkspaceActionPayload;
  onOpenWorkspaceHub?: (tab: 'docs' | 'sheets' | 'slides' | 'excel' | 'gmail') => void;
}

export const WorkspaceActionCard: React.FC<WorkspaceActionCardProps> = ({
  action,
  onOpenWorkspaceHub,
}) => {
  const { user, workspaceToken, getValidWorkspaceToken, signInWithGoogle } = useJarvisSession();
  const [loading, setLoading] = useState<boolean>(false);
  const [createdUrl, setCreatedUrl] = useState<string | null>(action.createdUrl || null);
  const [statusText, setStatusText] = useState<string | null>(
    action.createdUrl
      ? `Created in Google ${
          action.type === 'slides'
            ? 'Slides'
            : action.type === 'doc'
            ? 'Docs'
            : action.type === 'sheet'
            ? 'Sheets'
            : 'Workspace'
        }!`
      : null
  );
  const [isError, setIsError] = useState<boolean>(false);

  // Email state & confirmation controls
  const [emailTo, setEmailTo] = useState<string>(action.emailData?.to || '');
  const [emailSubject, setEmailSubject] = useState<string>(action.emailData?.subject || action.title || '');
  const [emailBody, setEmailBody] = useState<string>(action.emailData?.body || '');
  const [showSendConfirm, setShowSendConfirm] = useState<boolean>(false);
  const [isEmailSent, setIsEmailSent] = useState<boolean>(false);

  const ensureToken = async (): Promise<string | null> => {
    const token = await getValidWorkspaceToken();
    if (!token) {
      await signInWithGoogle();
      return await getValidWorkspaceToken();
    }
    return token;
  };

  const handleCreateInGoogle = async () => {
    setLoading(true);
    setStatusText(null);
    setIsError(false);

    try {
      const token = await ensureToken();
      if (!token) {
        setStatusText('Google Workspace sign-in required.');
        setIsError(true);
        setLoading(false);
        return;
      }

      if (action.type === 'slides') {
        const pres = await createGooglePresentation(
          token,
          action.title,
          action.slides || [
            {
              title: action.title,
              subtitle: 'Comprehensive Analysis',
              bullets: ['Generated by Jarvis AI', 'Ready for live presentation'],
            },
          ],
          action.theme
        );
        setCreatedUrl(pres.webViewLink || `https://docs.google.com/presentation/d/${pres.id}/edit`);
        setStatusText(
          `Presentation created in Google Slides (${action.slides?.length || 1} slides, ${action.theme?.name || 'Topic-Themed'})!`
        );
      } else if (action.type === 'doc') {
        const doc = await createGoogleDoc(token, action.title, action.docContent || action.summary);
        setCreatedUrl(doc.webViewLink || `https://docs.google.com/document/d/${doc.id}/edit`);
        setStatusText('Document created in Google Docs!');
      } else if (action.type === 'sheet') {
        const sheet = await createGoogleSheet(
          token,
          action.title,
          action.headers || ['Item', 'Description', 'Value'],
          action.rows || [['Sample 1', 'Detail', 100]]
        );
        setCreatedUrl(
          sheet.webViewLink || `https://docs.google.com/spreadsheets/d/${sheet.id}/edit`
        );
        setStatusText('Spreadsheet created in Google Sheets!');
      }
    } catch (err: any) {
      setStatusText(err?.message || 'Failed to create workspace item.');
      setIsError(true);
    } finally {
      setLoading(false);
    }
  };

  const handleSendEmailConfirmed = async () => {
    if (!emailTo.trim()) {
      setStatusText('Please enter a recipient email address.');
      setIsError(true);
      return;
    }

    setLoading(true);
    setStatusText(null);
    setIsError(false);

    try {
      const token = await ensureToken();
      if (!token) {
        setStatusText('Google Workspace sign-in required.');
        setIsError(true);
        setLoading(false);
        return;
      }

      const res = await sendGmailMessage(token, emailTo.trim(), emailSubject.trim(), emailBody);
      setIsEmailSent(true);
      setShowSendConfirm(false);
      setCreatedUrl('https://mail.google.com/mail/u/0/#inbox');
      setStatusText(`Email sent via Gmail API! Message ID: ${res.messageId}`);
    } catch (err: any) {
      setStatusText(err?.message || 'Failed to dispatch email via Gmail API.');
      setIsError(true);
    } finally {
      setLoading(false);
    }
  };

  const handleSaveGmailDraft = async () => {
    setLoading(true);
    setStatusText(null);
    setIsError(false);

    try {
      const token = await ensureToken();
      if (!token) {
        setStatusText('Google Workspace sign-in required.');
        setIsError(true);
        setLoading(false);
        return;
      }

      await createGmailDraft(token, emailTo.trim(), emailSubject.trim(), emailBody);
      setCreatedUrl('https://mail.google.com/mail/u/0/#drafts');
      setStatusText('Email saved to your Gmail Drafts folder!');
    } catch (err: any) {
      setStatusText(err?.message || 'Failed to save email draft.');
      setIsError(true);
    } finally {
      setLoading(false);
    }
  };

  const handleDownloadExcel = () => {
    try {
      const wb = createNewExcelWorkbook(
        `${action.title.replace(/\s+/g, '_')}.xlsx`,
        action.title.slice(0, 25),
        action.headers || ['Item', 'Category', 'Quantity', 'Cost ($)', 'Total ($)'],
        action.rows || [
          ['Alpha Initiative', 'Operations', 10, 150, 1500],
          ['Beta Deployment', 'Technology', 5, 300, 1500],
        ]
      );
      downloadExcelFile(wb);
      setStatusText('Excel (.xlsx) file exported to your downloads!');
      setIsError(false);
    } catch (err: any) {
      setStatusText(err?.message || 'Failed to export Excel file.');
      setIsError(true);
    }
  };

  const badgeConfig = {
    slides: {
      icon: '📽️',
      name: 'Google Slides Presentation',
      bg: 'bg-amber-500/10 border-amber-500/30 text-amber-700 dark:text-amber-300',
      btn: 'bg-amber-600 hover:bg-amber-500 text-white',
    },
    doc: {
      icon: '📄',
      name: 'Google Docs Document',
      bg: 'bg-blue-500/10 border-blue-500/30 text-blue-700 dark:text-blue-300',
      btn: 'bg-blue-600 hover:bg-blue-500 text-white',
    },
    sheet: {
      icon: '📊',
      name: 'Google Sheets Spreadsheet',
      bg: 'bg-emerald-500/10 border-emerald-500/30 text-emerald-700 dark:text-emerald-300',
      btn: 'bg-emerald-600 hover:bg-emerald-500 text-white',
    },
    excel: {
      icon: '📗',
      name: 'Microsoft Excel (.xlsx)',
      bg: 'bg-emerald-500/10 border-emerald-500/40 text-emerald-700 dark:text-emerald-300',
      btn: 'bg-emerald-600 hover:bg-emerald-500 text-white',
    },
    email: {
      icon: '✉️',
      name: 'Gmail Message (Review First)',
      bg: 'bg-red-500/10 border-red-500/30 text-red-700 dark:text-red-300',
      btn: 'bg-red-600 hover:bg-red-500 text-white',
    },
  }[action.type];

  const slideTheme = action.theme;

  return (
    <div className="w-full max-w-xl my-3 p-4 rounded-xl border border-neutral-300 dark:border-neutral-800 bg-white/95 dark:bg-[#0c0c0c] shadow-lg text-black dark:text-white transition select-none">
      {/* Top Banner */}
      <div className="flex items-center justify-between gap-2 pb-2.5 border-b border-neutral-200 dark:border-neutral-800/80">
        <div className="flex items-center gap-2">
          <span className="text-lg">{badgeConfig.icon}</span>
          <div>
            <div className="text-xs font-semibold tracking-wide flex items-center gap-2 flex-wrap">
              <span>{action.title}</span>
              <span className={`text-[10px] uppercase font-mono px-1.5 py-0.5 rounded border ${badgeConfig.bg}`}>
                {badgeConfig.name}
              </span>
              {action.type === 'slides' && slideTheme && (
                <span className="text-[10px] font-mono px-1.5 py-0.5 rounded bg-neutral-100 dark:bg-neutral-800 text-neutral-600 dark:text-neutral-300 border border-neutral-300 dark:border-neutral-700">
                  {slideTheme.name}
                </span>
              )}
            </div>
            <p className="text-[11px] text-neutral-500 dark:text-neutral-400">
              {action.summary}
            </p>
          </div>
        </div>

        {workspaceToken && action.type !== 'excel' && (
          <span className="text-[10px] text-emerald-600 dark:text-emerald-400 font-mono flex items-center gap-1 shrink-0">
            <span className="w-1.5 h-1.5 rounded-full bg-emerald-500"></span>
            Connected
          </span>
        )}
      </div>

      {/* Content Preview Stage */}
      <div className="py-3 text-xs">
        {/* Google Slides Themed Preview */}
        {action.type === 'slides' && action.slides && (
          <div className="space-y-2.5">
            <div className="flex items-center justify-between text-[11px] font-semibold text-neutral-600 dark:text-neutral-400">
              <span>Topic-Themed Slide Architecture ({action.slides.length} slides):</span>
              {slideTheme && (
                <span className="flex items-center gap-1.5 text-[10px] font-mono text-neutral-500">
                  <span
                    className="w-2.5 h-2.5 rounded-full border border-white/40"
                    style={{ backgroundColor: slideTheme.hexBg }}
                  />
                  <span>Theme: {slideTheme.name}</span>
                </span>
              )}
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
              {action.slides.slice(0, 4).map((s, idx) => (
                <div
                  key={idx}
                  className="p-3 rounded-lg border border-neutral-700/60 shadow-xs relative overflow-hidden transition"
                  style={{
                    backgroundColor: slideTheme?.hexBg || '#0A192F',
                    color: slideTheme?.hexBody || '#E2E8F0',
                  }}
                >
                  <div
                    className="font-bold text-xs truncate"
                    style={{ color: slideTheme?.hexTitle || '#38BDF8' }}
                  >
                    {idx + 1}. {s.title}
                  </div>
                  {s.subtitle && (
                    <div
                      className="text-[10px] italic mt-0.5 truncate"
                      style={{ color: slideTheme?.hexTitle || '#38BDF8', opacity: 0.85 }}
                    >
                      {s.subtitle}
                    </div>
                  )}
                  <ul className="text-[10.5px] space-y-1 mt-1.5 opacity-90">
                    {s.bullets.slice(0, 3).map((bullet, bIdx) => (
                      <li key={bIdx} className="line-clamp-2 leading-tight">
                        • {bullet}
                      </li>
                    ))}
                  </ul>
                </div>
              ))}
            </div>
            {action.slides.length > 4 && (
              <div className="text-[10.5px] text-neutral-500 dark:text-neutral-400 text-right">
                + {action.slides.length - 4} more slides in deck
              </div>
            )}
          </div>
        )}

        {/* Gmail Composition & Mandatory Review Section */}
        {action.type === 'email' && (
          <div className="space-y-2.5">
            <div className="p-2.5 rounded-lg bg-amber-50 dark:bg-amber-950/20 border border-amber-300 dark:border-amber-800 text-amber-800 dark:text-amber-300 text-[11px] flex items-center justify-between">
              <span className="font-semibold">⚠️ Safety Protocol: Review Email Before Sending</span>
              <span className="text-[10px] opacity-80">Requires Confirmation</span>
            </div>

            <div className="space-y-2 text-xs">
              <div>
                <label className="block text-[11px] font-medium text-neutral-500 mb-0.5">
                  Recipient (To:)
                </label>
                <input
                  type="email"
                  value={emailTo}
                  onChange={(e) => setEmailTo(e.target.value)}
                  placeholder="recipient@example.com"
                  className="w-full px-2.5 py-1.5 rounded-lg border border-neutral-300 dark:border-neutral-700 bg-white dark:bg-black text-xs font-mono"
                />
              </div>

              <div>
                <label className="block text-[11px] font-medium text-neutral-500 mb-0.5">
                  Subject Line:
                </label>
                <input
                  type="text"
                  value={emailSubject}
                  onChange={(e) => setEmailSubject(e.target.value)}
                  placeholder="Email subject..."
                  className="w-full px-2.5 py-1.5 rounded-lg border border-neutral-300 dark:border-neutral-700 bg-white dark:bg-black text-xs font-semibold"
                />
              </div>

              <div>
                <label className="block text-[11px] font-medium text-neutral-500 mb-0.5">
                  Message Body:
                </label>
                <textarea
                  value={emailBody}
                  onChange={(e) => setEmailBody(e.target.value)}
                  rows={5}
                  className="w-full px-2.5 py-1.5 rounded-lg border border-neutral-300 dark:border-neutral-700 bg-white dark:bg-black text-xs leading-relaxed font-sans"
                />
              </div>
            </div>

            {/* Confirmation Dialog before sending */}
            {showSendConfirm && (
              <div className="p-3 rounded-xl bg-red-50 dark:bg-red-950/40 border border-red-300 dark:border-red-800 text-xs text-red-800 dark:text-red-200 space-y-2">
                <div className="font-bold flex items-center gap-1.5">
                  <span>Confirm Outgoing Email Dispatch</span>
                </div>
                <p className="text-[11px] leading-snug">
                  Are you sure you want to send this email to{' '}
                  <span className="font-mono font-semibold">{emailTo}</span> with subject{' '}
                  <span className="font-semibold">"{emailSubject}"</span>?
                </p>
                <div className="flex items-center gap-2 pt-1">
                  <button
                    type="button"
                    onClick={handleSendEmailConfirmed}
                    disabled={loading}
                    className="px-3 py-1.5 rounded-lg bg-red-600 hover:bg-red-700 text-white font-semibold text-xs transition cursor-pointer disabled:opacity-50"
                  >
                    {loading ? 'Sending...' : 'Yes, Send Email Now'}
                  </button>
                  <button
                    type="button"
                    onClick={() => setShowSendConfirm(false)}
                    className="px-3 py-1.5 rounded-lg bg-neutral-200 dark:bg-neutral-800 hover:bg-neutral-300 dark:hover:bg-neutral-700 text-black dark:text-white text-xs font-medium transition cursor-pointer"
                  >
                    Cancel
                  </button>
                </div>
              </div>
            )}
          </div>
        )}

        {/* Google Doc Preview */}
        {action.type === 'doc' && action.docContent && (
          <div className="p-3 rounded-lg border border-neutral-200 dark:border-neutral-800 bg-neutral-50 dark:bg-[#141414] max-h-36 overflow-y-auto font-mono text-[11px] text-neutral-700 dark:text-neutral-300 whitespace-pre-wrap leading-relaxed">
            {action.docContent.slice(0, 500)}
            {action.docContent.length > 500 && '...'}
          </div>
        )}

        {/* Google Sheet & Excel Table Preview */}
        {(action.type === 'sheet' || action.type === 'excel') && action.headers && action.rows && (
          <div className="overflow-x-auto rounded-lg border border-neutral-200 dark:border-neutral-800 max-h-36">
            <table className="w-full text-left text-[11px] border-collapse">
              <thead>
                <tr className="bg-neutral-100 dark:bg-neutral-900 border-b border-neutral-200 dark:border-neutral-800 font-semibold text-neutral-700 dark:text-neutral-300">
                  {action.headers.map((h, i) => (
                    <th key={i} className="px-2.5 py-1.5 border-r border-neutral-200 dark:border-neutral-800">
                      {h}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {action.rows.slice(0, 4).map((row, rIdx) => (
                  <tr
                    key={rIdx}
                    className="border-b border-neutral-200/60 dark:border-neutral-800/60 text-neutral-600 dark:text-neutral-400"
                  >
                    {row.map((cell, cIdx) => (
                      <td
                        key={cIdx}
                        className="px-2.5 py-1 border-r border-neutral-200/60 dark:border-neutral-800/60 truncate max-w-[120px]"
                      >
                        {String(cell ?? '')}
                      </td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>

      {/* Status Feedback Banner */}
      {statusText && (
        <div
          className={`mb-2.5 px-3 py-1.5 rounded-lg text-xs flex items-center justify-between ${
            isError
              ? 'bg-red-50 text-red-700 dark:bg-red-950/40 dark:text-red-300 border border-red-300 dark:border-red-800'
              : 'bg-emerald-50 text-emerald-700 dark:bg-emerald-950/40 dark:text-emerald-300 border border-emerald-300 dark:border-emerald-800'
          }`}
        >
          <span className="truncate">{statusText}</span>
          {createdUrl && (
            <a
              href={createdUrl}
              target="_blank"
              rel="noreferrer"
              className="font-semibold underline ml-2 shrink-0"
            >
              Open in Google ↗
            </a>
          )}
        </div>
      )}

      {/* Action Buttons */}
      <div className="flex items-center justify-between gap-2 pt-2 border-t border-neutral-200 dark:border-neutral-800/80 flex-wrap">
        <div className="flex items-center gap-2 flex-wrap">
          {action.type === 'email' ? (
            <>
              {!isEmailSent && !showSendConfirm && (
                <button
                  type="button"
                  onClick={() => setShowSendConfirm(true)}
                  disabled={loading}
                  className="px-3.5 py-1.5 rounded-lg text-xs font-semibold bg-red-600 hover:bg-red-500 text-white transition flex items-center gap-1.5 shadow-sm cursor-pointer disabled:opacity-50"
                >
                  <span>✉️ Review &amp; Send via Gmail</span>
                </button>
              )}

              {!isEmailSent && (
                <button
                  type="button"
                  onClick={handleSaveGmailDraft}
                  disabled={loading}
                  className="px-3 py-1.5 rounded-lg text-xs font-medium border border-neutral-300 dark:border-neutral-700 bg-neutral-100 hover:bg-neutral-200 dark:bg-neutral-900 dark:hover:bg-neutral-800 text-black dark:text-white transition flex items-center gap-1 cursor-pointer disabled:opacity-50"
                >
                  <span>💾 Save as Draft</span>
                </button>
              )}
            </>
          ) : action.type !== 'excel' ? (
            !createdUrl ? (
              <button
                type="button"
                onClick={handleCreateInGoogle}
                disabled={loading}
                className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition flex items-center gap-1.5 shadow-sm disabled:opacity-50 cursor-pointer ${badgeConfig.btn}`}
              >
                {loading ? (
                  <>
                    <span className="w-3 h-3 border-2 border-white border-t-transparent rounded-full animate-spin"></span>
                    <span>Creating in Google...</span>
                  </>
                ) : (
                  <>
                    <span>
                      ✨ Create in{' '}
                      {action.type === 'slides'
                        ? 'Google Slides'
                        : action.type === 'doc'
                        ? 'Google Docs'
                        : 'Google Sheets'}
                    </span>
                  </>
                )}
              </button>
            ) : null
          ) : (
            <button
              type="button"
              onClick={handleDownloadExcel}
              className="px-3.5 py-1.5 rounded-lg text-xs font-semibold bg-emerald-600 hover:bg-emerald-500 text-white transition flex items-center gap-1.5 shadow-sm cursor-pointer"
            >
              <span>⬇ Download Excel (.xlsx)</span>
            </button>
          )}

          {createdUrl && (
            <a
              href={createdUrl}
              target="_blank"
              rel="noreferrer"
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition flex items-center gap-1 shadow-sm ${
                action.type === 'email'
                  ? 'border border-neutral-300 dark:border-neutral-700 bg-neutral-100 hover:bg-neutral-200 dark:bg-neutral-900 dark:hover:bg-neutral-800 text-black dark:text-white'
                  : badgeConfig.btn
              }`}
            >
              <span>
                {action.type === 'slides'
                  ? 'Open in Google Slides'
                  : action.type === 'doc'
                  ? 'Open in Google Docs'
                  : action.type === 'sheet'
                  ? 'Open in Google Sheets'
                  : 'View Online'}
              </span>
              <span>↗</span>
            </a>
          )}

          {createdUrl && action.type === 'slides' && action.theme && (
            <button
              type="button"
              onClick={async () => {
                const match = createdUrl.match(/\/d\/([a-zA-Z0-9-_]+)/);
                if (!match) return;
                setLoading(true);
                try {
                  const token = await ensureToken();
                  if (!token) return;
                  await applyThemeToPresentation(token, match[1], action.theme!);
                  setStatusText(
                    `Theme "${action.theme?.name}" dynamically applied to Google Slides presentation!`
                  );
                } catch (err: any) {
                  setStatusText(err?.message || 'Failed to apply theme to slides.');
                  setIsError(true);
                } finally {
                  setLoading(false);
                }
              }}
              disabled={loading}
              className="px-3 py-1.5 rounded-lg text-xs font-medium border border-amber-300 dark:border-amber-700 bg-amber-50 hover:bg-amber-100 dark:bg-amber-950/40 dark:hover:bg-amber-900/50 text-amber-800 dark:text-amber-200 transition flex items-center gap-1 cursor-pointer disabled:opacity-50"
              title="Apply color palette, background, and fonts directly to this presentation"
            >
              <span>🎨 Apply Theme</span>
            </button>
          )}
        </div>

        {onOpenWorkspaceHub && (
          <button
            type="button"
            onClick={() => {
              const tab =
                action.type === 'slides'
                  ? 'slides'
                  : action.type === 'doc'
                  ? 'docs'
                  : action.type === 'sheet'
                  ? 'sheets'
                  : action.type === 'email'
                  ? 'gmail'
                  : 'excel';
              onOpenWorkspaceHub(tab);
            }}
            className="text-xs text-neutral-500 hover:text-black dark:hover:text-white transition underline cursor-pointer"
          >
            Open in Office Hub →
          </button>
        )}
      </div>
    </div>
  );
};
